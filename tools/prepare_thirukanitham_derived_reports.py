#!/usr/bin/env python3
"""Rebuild the explicitly profile-derived Thirukanitham report inventory."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path


OUT = Path("tests/reference/calendar-thirukanitham-v1/derived-civil-day-and-month-reports.json")
COMMAND = [
    "test",
    "-p",
    "tamil-numerals",
    "calendar::drik::tests::dump_independent_transition_reference_candidates",
    "--",
    "--ignored",
    "--nocapture",
]


def cargo_command() -> str:
    found = shutil.which("cargo")
    if found:
        return found
    profile = os.environ.get("USERPROFILE")
    if profile:
        candidate = Path(profile) / ".cargo" / "bin" / "cargo.exe"
        if candidate.is_file():
            return str(candidate)
    raise RuntimeError("cargo was not found on PATH or under the current Windows profile")


def main() -> None:
    completed = subprocess.run(
        [cargo_command(), *COMMAND],
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    rows: dict[str, list[dict[str, object]]] = {
        "CANDIDATE": [],
        "DAYREPORT": [],
        "MONTHREF": [],
    }
    for line in (completed.stdout + "\n" + completed.stderr).splitlines():
        for prefix in rows:
            marker = f"{prefix} "
            index = line.find(marker)
            if index >= 0:
                rows[prefix].append(json.loads(line[index + len(marker) :]))
                break
    if len(rows["CANDIDATE"]) != 8 or len(rows["DAYREPORT"]) != 40 or len(rows["MONTHREF"]) != 49:
        raise RuntimeError(
            "unexpected derived inventory sizes: "
            f"candidates={len(rows['CANDIDATE'])}, days={len(rows['DAYREPORT'])}, "
            f"months={len(rows['MONTHREF'])}"
        )
    output = {
        "evidence_class": "derived regression and coverage evidence; these values are generated by the pinned Rust profile and are not independent expected astronomy",
        "definition_id": "thirukanitham-astro-2.0.0-lahiri-p03-apparent-v2",
        "reproduction": "python tools/prepare_thirukanitham_derived_reports.py; invokes cargo test -p tamil-numerals calendar::drik::tests::dump_independent_transition_reference_candidates -- --ignored --nocapture and retains DAYREPORT, MONTHREF and CANDIDATE records",
        "civil_day_reports": rows["DAYREPORT"],
        "month_coverage": rows["MONTHREF"],
        "event_witnesses": rows["CANDIDATE"],
    }
    OUT.write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(rows['DAYREPORT'])} reports, {len(rows['MONTHREF'])} month rows, and {len(rows['CANDIDATE'])} witnesses")
    print(f"output: {OUT}")


if __name__ == "__main__":
    main()
